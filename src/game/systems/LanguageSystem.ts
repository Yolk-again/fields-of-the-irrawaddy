export class LanguageSystem {
  private language: Language = "my";
  private listeners: Array<() => void> = [];

  private storageKey = "fields_of_irrawaddy_language";

  constructor() {
    try {
      const saved = window.localStorage.getItem(this.storageKey);

      if (saved === "my" || saved === "en") {
        this.language = saved;
      }
    } catch {
      this.language = "my";
    }
  }

  getLanguage(): Language {
    return this.language;
  }

  getFontFamily(): string {
    // Keep both families in the stack so mixed Burmese + English strings are
    // shaped with their intended glyph sets in the same canvas text object.
    return '"Noto Sans", "Noto Sans Myanmar", "Myanmar Text", "Leelawadee UI", "Segoe UI", Arial, sans-serif';
  }

  t(
    key: string,
    values: Record<string, string | number> = {}
  ): string {
    let result =
      translations[this.language][key] ??
      translations.en[key] ??
      key;

    for (const [name, value] of Object.entries(values)) {
      result = result.replace(
        new RegExp(`\\{${name}\\}`, "g"),
        String(value)
      );
    }

    return result;
  }

  setLanguage(language: Language): void {
    if (this.language === language) {
      return;
    }

    this.language = language;

    try {
      window.localStorage.setItem(
        this.storageKey,
        language
      );
    } catch {
      // Continue using the selected language for this session.
    }

    this.notify();
  }

  toggleLanguage(): void {
    this.setLanguage(
      this.language === "en" ? "my" : "en"
    );
  }

  onChange(callback: () => void): void {
    this.listeners.push(callback);
  }

  private notify(): void {
    for (const callback of this.listeners) {
      callback();
    }
  }
}
